import { Injectable, InternalServerErrorException, Logger } from '@nestjs/common';
import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';

/**
 * Server-side PDF generation for ONET quotations.
 *
 * pdfmake's npm package does not expose its package.json consistently across
 * package-manager/version combinations, and some installations omit the
 * examples/fonts directory. Resolve fonts from multiple supported locations,
 * then fall back to the Roboto fonts embedded in pdfmake's vfs_fonts bundle.
 */
@Injectable()
export class PdfService {
  private readonly logger = new Logger(PdfService.name);

  async quotation(data: any): Promise<Buffer> {
    try {
      // eslint-disable-next-line @typescript-eslint/no-var-requires
      const PdfPrinter = require('pdfmake');
      const fonts = this.resolveRobotoFonts();
      const printer = new PdfPrinter(fonts);
      const rev = data.revisions?.[0];
      const lines = rev?.lineItems ?? [];
      const money = (value: unknown) => Number(value ?? 0).toLocaleString('en-LK', {
        minimumFractionDigits: 2,
        maximumFractionDigits: 2,
      });

      const body: any[][] = [[
        { text: 'Description', bold: true },
        { text: 'Qty', bold: true, alignment: 'right' },
        { text: 'Unit price (LKR)', bold: true, alignment: 'right' },
        { text: 'Total (LKR)', bold: true, alignment: 'right' },
      ]];

      for (const line of lines) {
        body.push([
          String(line.description ?? 'Item'),
          String(line.quantity ?? 1),
          { text: money(line.unitPrice), alignment: 'right' },
          { text: money(line.total), alignment: 'right' },
        ]);
      }
      if (lines.length === 0) {
        body.push(['See quotation snapshot', '1', '-', { text: money(rev?.total), alignment: 'right' }]);
      }

      const documentDefinition: any = {
        pageSize: 'A4',
        pageMargins: [40, 50, 40, 50],
        defaultStyle: { font: 'Roboto', fontSize: 9 },
        content: [
          { text: 'ONET', fontSize: 20, bold: true, color: '#17365D' },
          { text: 'ENCLOSURE COSTING & QUOTATION', fontSize: 10, color: '#666666', margin: [0, 0, 0, 18] },
          {
            columns: [
              [
                { text: `Quotation: ${data.quotationNo ?? data.id ?? ''}`, bold: true },
                { text: `Date: ${data.createdAt ? new Date(data.createdAt).toLocaleDateString('en-GB') : new Date().toLocaleDateString('en-GB')}` },
                { text: `Status: ${data.status ?? 'DRAFT'}` },
              ],
              [
                { text: 'Customer', bold: true },
                { text: data.customer?.name ?? 'Customer not specified' },
                { text: data.customer?.email ?? '' },
                { text: data.customer?.phone ?? '' },
                { text: data.customer?.address ?? '' },
              ],
            ],
            columnGap: 20,
            margin: [0, 0, 0, 20],
          },
          { table: { headerRows: 1, widths: ['*', 35, 100, 100], body }, layout: 'lightHorizontalLines' },
          {
            columns: [
              { text: '' },
              {
                width: 170,
                table: {
                  widths: ['*', 100],
                  body: [
                    ['Subtotal', money(rev?.subtotal)],
                    ...(rev?.tax !== undefined ? [['Tax', money(rev?.tax)]] : []),
                    ['Grand total', { text: money(rev?.total), bold: true }],
                  ],
                },
                layout: 'noBorders',
              },
            ],
            margin: [0, 20, 0, 20],
          },
          { text: 'Terms and conditions', bold: true, margin: [0, 10, 0, 5] },
          {
            text: rev?.snapshot?.terms ?? 'Prices are subject to confirmation. This quotation is valid for the period agreed with the customer.',
            fontSize: 9,
            color: '#444444',
          },
          {
            text: 'Generated by ONET Enclosure Costing & Quotation System',
            fontSize: 8,
            color: '#777777',
            alignment: 'center',
            margin: [0, 30, 0, 0],
          },
        ],
        footer: (currentPage: number, pageCount: number) => ({
          text: `Page ${currentPage} of ${pageCount}`,
          alignment: 'center',
          fontSize: 8,
          margin: [0, 20, 0, 0],
        }),
      };

      const pdf = printer.createPdfKitDocument(documentDefinition);
      const chunks: Buffer[] = [];
      return await new Promise<Buffer>((resolve, reject) => {
        pdf.on('data', (chunk: Buffer) => chunks.push(chunk));
        pdf.on('end', () => resolve(Buffer.concat(chunks)));
        pdf.on('error', reject);
        pdf.end();
      });
    } catch (error) {
      const detail = error instanceof Error ? `${error.message}\n${error.stack ?? ''}` : String(error);
      this.logger.error(`Quotation PDF generation failed: ${detail}`);
      throw new InternalServerErrorException(
        'PDF generation failed. Check the backend console for the underlying error. Confirm pdfmake is installed and its Roboto fonts are available.',
      );
    }
  }

  private resolveRobotoFonts(): { Roboto: { normal: string; bold: string; italics: string; bolditalics: string } } {
    const filenames = {
      normal: 'Roboto-Regular.ttf',
      bold: 'Roboto-Medium.ttf',
      italics: 'Roboto-Italic.ttf',
      bolditalics: 'Roboto-MediumItalic.ttf',
    };

    const candidates: string[] = [];
    try {
      // Do not resolve pdfmake/package.json: package exports can block it.
      const entry = require.resolve('pdfmake');
      const packageRoot = path.resolve(path.dirname(entry), '..');
      candidates.push(path.join(packageRoot, 'examples', 'fonts'));
      candidates.push(path.join(packageRoot, 'fonts'));
      candidates.push(path.join(path.dirname(entry), '..', 'examples', 'fonts'));
    } catch (error) {
      this.logger.warn(`Could not locate pdfmake entry file: ${String(error)}`);
    }

    for (const directory of candidates) {
      const result = {
        normal: path.join(directory, filenames.normal),
        bold: path.join(directory, filenames.bold),
        italics: path.join(directory, filenames.italics),
        bolditalics: path.join(directory, filenames.bolditalics),
      };
      if (Object.values(result).every((file) => fs.existsSync(file))) return { Roboto: result };
    }

    // Fallback: pdfmake ships the Roboto TTF files base64-encoded in vfs_fonts.
    // Materialize those bundled fonts to a deterministic temp folder for PdfPrinter.
    try {
      // eslint-disable-next-line @typescript-eslint/no-var-requires
      const bundle = require('pdfmake/build/vfs_fonts');
      const vfs = bundle?.pdfMake?.vfs
        ?? bundle?.default?.pdfMake?.vfs
        ?? bundle?.vfs
        ?? bundle?.default?.vfs
        ?? (bundle?.[filenames.normal] ? bundle : undefined);
      if (vfs) {
        const directory = path.join(os.tmpdir(), 'onet-pdfmake-roboto');
        fs.mkdirSync(directory, { recursive: true });
        const result: Record<string, string> = {};
        for (const [key, filename] of Object.entries(filenames)) {
          const encoded = vfs[filename];
          if (typeof encoded !== 'string' || encoded.length === 0) {
            throw new Error(`Roboto font ${filename} was not found in pdfmake/build/vfs_fonts`);
          }
          const target = path.join(directory, filename);
          if (!fs.existsSync(target) || fs.statSync(target).size === 0) {
            fs.writeFileSync(target, Buffer.from(encoded, 'base64'));
          }
          result[key] = target;
        }
        return { Roboto: result as { normal: string; bold: string; italics: string; bolditalics: string } };
      }
    } catch (error) {
      this.logger.warn(`Could not extract bundled Roboto fonts: ${error instanceof Error ? error.message : String(error)}`);
    }

    throw new Error(
      'Roboto TTF files were not found. Checked pdfmake examples/fonts and fonts directories, then pdfmake/build/vfs_fonts.',
    );
  }
}
